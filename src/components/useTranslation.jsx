export function useTranslation() {
  const { data: user } = useQuery({
    queryKey: ['currentUser'],
    queryFn: () => base44.auth.me(),
    retry: false,
  });

  const language = user?.preferred_language || 'ko';

  const t = (key) => {
    return translations[language]?.[key] || translations['ko'][key] || key;
  };

  return { t, language };
}